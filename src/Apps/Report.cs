using System.Globalization;
using System.Net;
using System.Text;
using TraceMe.Engine;
using TraceMe.Models;

namespace TraceMe.Apps;

/// <summary>Self-contained, printable HTML report for a finished (or running) app session.</summary>
public static class ReportBuilder
{
    static string E(string? s) => WebUtility.HtmlEncode(s ?? "");
    static string N(double? v, int d = 1) => v == null ? "–" : v.Value.ToString("F" + d, CultureInfo.InvariantCulture);

    static string Chart(Hub hub, string tid, long from, long to)
    {
        var t = hub.Targets.Get(tid);
        int hop = t?.DestinationHop()?.Hop ?? t?.HopsList().LastOrDefault(h => h.Recv > 0)?.Hop ?? 0;
        if (hop == 0 || to <= from) return "<p class='mute'>No timeline data.</p>";
        const int W = 760, H = 140, L = 42, R = 8, T = 8, B = 20;
        var b = hub.Db.Timeline(tid, hop, from, to, 150);
        if (b.Length == 0) return "<p class='mute'>No timeline data.</p>";
        double max = Math.Max(10, b.Where(x => x.Max != null).Select(x => x.Max!.Value).DefaultIfEmpty(10).Max() * 1.1);
        double X(long ts) => L + (ts - from) / (double)(to - from) * (W - L - R);
        double Y(double v) => T + (H - T - B) * (1 - Math.Min(1, v / max));
        double bw = Math.Max(1.5, (to - from) / 150.0 / (to - from) * (W - L - R));
        var sb = new StringBuilder($"<svg viewBox='0 0 {W} {H}' width='100%' role='img' aria-label='Latency over time'>");
        for (int i = 0; i <= 4; i++)
        {
            double v = max * i / 4, y = Y(v);
            sb.Append($"<line x1='{L}' x2='{W - R}' y1='{y:F1}' y2='{y:F1}' stroke='#e5e7eb'/><text x='{L - 4}' y='{y + 3:F1}' font-size='9' text-anchor='end' fill='#6b7280'>{v:0}</text>");
        }
        foreach (var x in b)
        {
            int lost = x.N - x.R;
            if (lost > 0) sb.Append($"<rect x='{X(x.T):F1}' y='{T}' width='{bw:F1}' height='{H - T - B}' fill='#dc2626' opacity='{Math.Min(1, .25 + .75 * lost / x.N):F2}'/>");
            if (x.R > 0 && x.Min != null && x.Max != null) sb.Append($"<rect x='{X(x.T):F1}' y='{Y(x.Max.Value):F1}' width='{bw:F1}' height='{Math.Max(1.5, Y(x.Min.Value) - Y(x.Max.Value)):F1}' fill='#93c5fd'/>");
        }
        var pts = b.Where(x => x.R > 0 && x.Avg != null).Select(x => $"{X(x.T) + bw / 2:F1},{Y(x.Avg!.Value):F1}");
        sb.Append($"<polyline fill='none' stroke='#2563eb' stroke-width='1.6' points='{string.Join(' ', pts)}'/>");
        sb.Append($"<text x='{L}' y='{H - 5}' font-size='9' fill='#6b7280'>{DateTimeOffset.FromUnixTimeMilliseconds(from).LocalDateTime:HH:mm:ss}</text>");
        sb.Append($"<text x='{W - R}' y='{H - 5}' font-size='9' text-anchor='end' fill='#6b7280'>{DateTimeOffset.FromUnixTimeMilliseconds(to).LocalDateTime:HH:mm:ss}</text></svg>");
        return sb.ToString();
    }

    public static string Build(AppSession s, Hub hub)
    {
        long from = s.Started, to = s.Ended ?? DateTimeOffset.UtcNow.ToUnixTimeMilliseconds();
        var sum = s.Summary ?? new SessionSummary { Headline = s.Status == "running" ? "Session still running — verdicts below are live." : "No verdict available." };
        var sb = new StringBuilder();
        sb.Append("<!doctype html><html lang='en'><head><meta charset='utf-8'><meta name='viewport' content='width=device-width,initial-scale=1'>");
        sb.Append($"<title>Network report — {E(s.Name)}</title><style>");
        sb.Append("body{font:14px/1.5 'Segoe UI',system-ui,sans-serif;color:#111827;max-width:860px;margin:24px auto;padding:0 16px}h1{font-size:22px;margin:0}h2{font-size:16px;margin:26px 0 8px}");
        sb.Append(".mute{color:#6b7280}.card{border:1px solid #e5e7eb;border-radius:10px;padding:14px 16px;margin:12px 0}.ok{border-left:5px solid #16a34a}.warn{border-left:5px solid #d97706}.bad{border-left:5px solid #dc2626}");
        sb.Append("table{border-collapse:collapse;width:100%}th,td{padding:5px 8px;border-bottom:1px solid #e5e7eb;text-align:right}th{color:#6b7280;font-weight:500;font-size:12px}td:first-child,th:first-child,td.l,th.l{text-align:left}");
        sb.Append(".seg{display:flex;gap:6px;margin:8px 0}.seg div{flex:1;border:1px solid #e5e7eb;border-radius:8px;padding:6px 8px;font-size:12px}.seg .good{background:#f0fdf4}.seg .warn{background:#fffbeb}.seg .bad{background:#fef2f2;border-color:#dc2626}");
        sb.Append("@media print{body{margin:0}.card{break-inside:avoid}}</style></head><body>");
        sb.Append($"<h1>Network report — {E(s.Name)}</h1><div class='mute'>{DateTimeOffset.FromUnixTimeMilliseconds(from).LocalDateTime:yyyy-MM-dd HH:mm:ss} → {DateTimeOffset.FromUnixTimeMilliseconds(to).LocalDateTime:HH:mm:ss} · {TimeSpan.FromMilliseconds(to - from):hh\\:mm\\:ss} · {E(Environment.MachineName)} · generated by TraceMe</div>");
        string cls = sum.Code is "ok" ? "ok" : sum.Code is "no_data" or "insufficient" or "burst" ? "warn" : "bad";
        sb.Append($"<div class='card {cls}'><b>{E(sum.Headline)}</b></div>");
        sb.Append("<h2>Servers</h2><table><thead><tr><th>Server</th><th>Samples</th><th>Avg ms</th><th>P95 ms</th><th>Max ms</th><th>Jitter</th><th>Loss</th><th>MOS</th></tr></thead><tbody>");
        var servers = sum.Servers.Count > 0 ? sum.Servers : new List<ServerSummary>();
        foreach (var v in servers)
            sb.Append($"<tr><td>{E(v.Host ?? v.Ip)} <span class='mute'>{(v.Host != null ? E(v.Ip) : "")}</span></td><td>{v.Samples}</td><td>{N(v.Avg)}</td><td>{N(v.P95)}</td><td>{N(v.Max)}</td><td>{N(v.Jitter)}</td><td>{N(v.LossPct)}%</td><td>{N(v.Mos, 2)}</td></tr>");
        if (servers.Count == 0) sb.Append("<tr><td colspan='8' class='mute'>No servers were traced.</td></tr>");
        sb.Append("</tbody></table>");
        foreach (var srv in s.Servers)
        {
            var t = hub.Targets.Get(srv.TargetId); if (t == null) continue;
            var d = hub.Diagnosis.ForTarget(t, Math.Max(from, srv.FirstSeen - 5000), to);
            var c = d.Status switch { "ok" => "ok", "warn" => "warn", "bad" => "bad", _ => "warn" };
            sb.Append($"<h2>{E(srv.Ip)} <span class='mute'>({E(srv.Proto)} {(srv.Port > 0 ? srv.Port : "")})</span></h2>");
            sb.Append($"<div class='card {c}'><b>{E(d.Headline)}</b>");
            if (d.Evidence.Count > 0) sb.Append("<ul>" + string.Concat(d.Evidence.Select(x => $"<li>{E(x)}</li>")) + "</ul>");
            if (d.Advice.Count > 0 && d.Code is not "ok") sb.Append("<div class='mute'>What to do:</div><ul>" + string.Concat(d.Advice.Select(x => $"<li>{E(x)}</li>")) + "</ul>");
            sb.Append("</div><div class='seg'>" + string.Concat(d.Segments.Select(x => $"<div class='{x.Status}'><b>{E(x.Name)}</b><br>hops {x.FromHop}–{x.ToHop}<br>{N(x.Avg)} ms · {N(x.LossPct)}% loss</div>")) + "</div>");
            sb.Append(Chart(hub, srv.TargetId, from, to));
            var hops = t.VisibleHops();
            var stats = hub.Db.WindowStats(srv.TargetId, hops.Select(h => h.Hop), from, to);
            sb.Append("<table><thead><tr><th>Hop</th><th class='l'>Host</th><th>Sent</th><th>Loss</th><th>Avg</th><th>Max</th><th>Jitter</th></tr></thead><tbody>");
            foreach (var h in hops)
            {
                stats.TryGetValue(h.Hop, out var st);
                sb.Append($"<tr><td>{h.Hop}</td><td class='l'>{E(h.Address ?? "no response")}</td><td>{st?.Sent ?? 0}</td><td>{N(st?.LossPct)}%</td><td>{N(st?.Avg)}</td><td>{N(st?.Max)}</td><td>{N(st?.Jitter)}</td></tr>");
            }
            sb.Append("</tbody></table>");
        }
        sb.Append("<p class='mute' style='margin-top:28px'>Loss at an intermediate hop only counts when the hops after it lose packets too; routers that merely rate-limit ICMP replies are ignored. Game servers often do not answer probes, in which case the analysis covers the path up to the last responding hop.</p></body></html>");
        return sb.ToString();
    }
}
